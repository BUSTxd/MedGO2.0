// Capítulo 1 — ¿Por qué aparece? Una cerradura con tres llaves (genes,
// hormonas, ambiente): en el paso 0 se abre grande en el centro; desde el paso 1
// se queda a la izquierda y cada llave entra cuando la voz termina su apartado.
// Guion §1. Los `at` salen de la hora de cada frase en el audio (ms desde el
// inicio del paso); el verificador exige que nada pase del final de su frase.

