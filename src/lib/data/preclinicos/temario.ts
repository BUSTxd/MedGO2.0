/**
 * Temario universal de las ciencias básicas: el esqueleto de Preclínicos, el
 * producto central de `/estudio` (Cayetano y los exámenes son metas encima).
 *
 * Se guía por el USMLE Step 1 y por el temario público del IFOM BSE (NBME): un
 * curso por sistema, más «Principios generales», Bioestadística y Ética. Cada
 * sistema va en tres bloques (estructura y función → enfermedades → farmacología)
 * y cada tema lleva sus disciplinas y los puntos que hay que saber. La investigación
 * y las fuentes están en `docs/ciencias-basicas-universal.md`.
 *
 * Los ids son estables (`cb-<id>`): de ellos cuelgan las marcas del alumno y,
 * más adelante, resúmenes y banqueos. Cambiar un título no rompe nada; cambiar un
 * id, sí.
 */

export type Disciplina = 'ANA' | 'EMB' | 'HIS' | 'BIO' | 'GEN' | 'FIS' | 'INM' | 'MIC' | 'PAT' | 'FAR' | 'CON' | 'EPI';

export const DISCIPLINAS: Record<Disciplina, string> = {
  ANA: 'Anatomía',
  EMB: 'Embriología',
  HIS: 'Histología',
  BIO: 'Bioquímica',
  GEN: 'Genética',
  FIS: 'Fisiología',
  INM: 'Inmunología',
  MIC: 'Microbiología',
  PAT: 'Patología',
  FAR: 'Farmacología',
  CON: 'Ciencias de la conducta',
  EPI: 'Bioestadística y epidemiología',
};

export interface TemaBasico {
  /** Sin el prefijo `cb-`, que pone `idTemaBasico`. */
  id: string;
  titulo: string;
  disciplinas: Disciplina[];
  puntos: string[];
}

export interface BloqueBasico {
  nombre: string;
  temas: TemaBasico[];
}

export interface SistemaBasico {
  slug: string;
  nombre: string;
  /** Lo que pesa en el USMLE Step 1 (algunos sistemas van en pareja). */
  peso: string;
  bloques: BloqueBasico[];
}

export const idTemaBasico = (t: TemaBasico) => `cb-${t.id}`;

/** `t('id', 'Título', 'FIS PAT', 'punto; punto; punto')`. */
const t = (id: string, titulo: string, disciplinas: string, puntos: string): TemaBasico => ({
  id,
  titulo,
  disciplinas: disciplinas.split(' ') as Disciplina[],
  puntos: puntos.split(';').map((p) => p.trim()).filter(Boolean),
});
const b = (nombre: string, ...temas: TemaBasico[]): BloqueBasico => ({ nombre, temas });

