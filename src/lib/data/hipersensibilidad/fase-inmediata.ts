import { DIST_IGE, FCERI, mastocitoConReceptores } from './sensibilizacion';

/** El mastocito ya sensibilizado: aparece con sus FcεRI y sus cuatro IgE. */
export function mastocitoSensibilizado(mast: string, iges: string[], pos: { col: number; row: number }, at = 0): Accion[] {
  return [
    { at, tipo: 'appear', actor: mast, pos },
    ...mastocitoConReceptores(mast, at + 200),
    ...iges.flatMap((k, i): Accion[] => [
      { at: at + 300 + i * 80, tipo: 'appear', actor: k, pos: { col: pos.col + Math.cos((FCERI[i] * Math.PI) / 180) * 1.3, row: pos.row + Math.sin((FCERI[i] * Math.PI) / 180) * 1.3 } },
      { at: at + 500 + i * 80, tipo: 'bind', actor: k, target: mast, ang: FCERI[i], dist: DIST_IGE, apunta: 'fc', duration: 500 },
    ]),
  ];
}

