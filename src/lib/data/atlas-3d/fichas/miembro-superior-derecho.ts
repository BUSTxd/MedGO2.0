const conNota = <T extends object>(f: T, nota?: string): T => (nota ? { ...f, nota } : f);

/** Vértebra torácica: `costales` = fositas propias de ese nivel. */
const toracica = (costales: string[], espinosa: string, articulaciones: string, nota?: string): FichaHueso =>
  conNota<FichaHueso>({
    tipo: 'hueso',
    clase: 'Irregular',
    partes: [
      'Cuerpo vertebral (forma de corazón)',
      ...costales,
      'Pedículos y láminas',
      espinosa,
      'Apófisis articulares superiores e inferiores (carillas en plano frontal)',
      'Agujero vertebral pequeño y circular',
    ],
    articulaciones,
  }, nota);

