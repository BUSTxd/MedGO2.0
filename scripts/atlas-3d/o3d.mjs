// ─── Nombres del OBJ ─────────────────────────────────────────────────────────
// Los objetos traen el lado pegado de mil maneras («Humerus.r», «Scapula.r.»,
// «Talus.r_​», con espacios de ancho cero o tabuladores): todos son derechos.
export function limpiar(crudo) {
  let n = crudo.replace(/[​\t]/g, '').trim()
    .replace(/[._\s]+r[._\s]*$/i, '')
    .replace(/[._\s]+$/, '')
    .replace(/_/g, ' ').replace(/\s+/g, ' ').trim();
  return RENOMBRAR[n] ?? n;
}
