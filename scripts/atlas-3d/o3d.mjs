export function nombreDe(region, en) {
  const v = NOMBRES[en];
  if (v) return typeof v === 'string' ? v : v[region === 'miembro-superior-derecho' ? 's' : 'i'];
  for (const [re, f] of PATRONES) {
    const m = en.match(re);
    if (m) return f(...m.slice(1));
  }
  return null;
}

