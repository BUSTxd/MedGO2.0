export function sistemaDe(en) {
  if (EXCLUIR.has(en)) return null;
  if (SISTEMA_FIJO[en]) return SISTEMA_FIJO[en];
  if (HUESOS.has(en) || /^(Cervical|Thoracic|Lumbar) vertebra \(|^Rib \(\d|^Costal cart of|^\d(st|nd|rd|th) metacarpal bone$|phalanx of|^annulus fibrosus|^Nucleus pulposus/i.test(en)) return 'hueso';
  if (/vein|venous/i.test(en)) return 'vena';
  if (/nerve|plexus|root$|lumbosacral trunk|sympathic trunk|spinal cord/i.test(en)) return 'nervio';
  if (/arter|\barch$|arch\b(?! of)|perforating br|cervical trunk$|brachiocephalic/i.test(en)) return 'arteria';
  if (/ligament|\blig\b|capsule|bursa|sheath|vaginae|retinacul|fascia|aponeurosis|membrane|labrum|menisc|disc\b|art cart|articular cartilage|synovial|septum|tract|recess|fat pad|zona orbicularis|syndesmosis|symphysis|fibrous|extensor hood|extensor apparatus|lateral band|intertendinous|tendinous arch/i.test(en)) return 'conectivo';
  return 'musculo';
}

// ─── Zona ────────────────────────────────────────────────────────────────────
// Esqueleto axial y lo que va con él: la misma zona en las dos regiones, para
// que las piezas compartidas (T12-L5, sacro) no cambien de zona según qué
// región se cargó primero.
const AXIAL = /vertebra|^atlas|^axis|^art cart of (atlas|axis|sacrum)|sacrum|coccyx|sacrococcygeal|annulus fibrosus|nucleus pulposus|^rib \(|rib art cart|costal cart|sternum|manubrium|xiphoid|sternocostal|spinal cord|sympathic|arachnoid|intercornual/i;
// Lo que se añade de Z-Anatomy para las inserciones del trapecio (línea nucal
// superior, protuberancia occipital, ligamento nucal) y del platisma (mandíbula).
const CUELLO = new Set(['Platysma', 'Occipital bone', 'Mandible', 'Nuchal ligament']);

export const REGIONES_O3D = {
  'miembro-superior-derecho': {
    nombre: 'Miembro superior derecho',
    lado: 'derecho',
    // Cortes por la altura del centro (Open3DModel): bajo la escápula (1,255 m)
    // y la cabeza humeral → brazo; codo (1,10 m); muñeca (semilunar, 0,85-0,86 m).
    zona(en, [, y]) {
      if (CUELLO.has(en)) return 'cuello';
      if (AXIAL.test(en)) return 'tronco';
      if (y > 1.29) return 'hombro';
      if (y > 1.1) return 'brazo';
      if (y > 0.862) return 'antebrazo';
      return 'mano';
    },
  },
  'miembro-inferior-derecho': {
    nombre: 'Miembro inferior derecho',
    lado: 'derecho',
    // Cortes: bajo la cabeza femoral (0,88 m) y la tuberosidad isquiática;
    // sobre la rótula (0,42-0,47 m: la rodilla va con la pierna, como en el
    // sílabo); maléolos (0,075 m).
    zona(en, [, y]) {
      if (AXIAL.test(en)) return 'tronco';
      if (y > 0.83) return 'pelvis';
      if (y > 0.47) return 'muslo';
      if (y > 0.075) return 'pierna';
      return 'pie';
    },
  },
};

